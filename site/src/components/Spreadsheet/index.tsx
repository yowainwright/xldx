"use client";

import { useMemo, useState } from "react";
import { Effect, Result } from "effect";
import { FormulaBar } from "./FormulaBar";
import { Grid } from "./Grid";
import { columnLabel, commitCell, createSpreadsheet, readInput, spillAt } from "./utils";

function useSpreadsheet() {
  const [book, setBook] = useState(createSpreadsheet);
  const [selected, setSelected] = useState({ row: 0, column: 0 });
  const [draft, setDraft] = useState(() => readInput(book.toJSON().sheets[0].data[0][0]));
  const [editing, setEditing] = useState(false);
  const [error, setError] = useState<string>();
  const calculation = useMemo(() => book.calculate(), [book]);
  const worksheet = calculation.workbook.sheets[0];
  const spills = worksheet.spills ?? [];
  const spill = spillAt(spills, selected.row, selected.column);
  const readOnly = Boolean(
    spill && (spill.row !== selected.row || spill.column !== selected.column),
  );
  const help =
    readOnly && spill
      ? `Generated by ${columnLabel(spill.column)}${spill.row + 1}. Select that cell to edit its formula.`
      : "Select a cell. Edit above, or double-click a cell. Enter saves; Escape cancels.";
  const address = `${columnLabel(selected.column)}${selected.row + 1}`;
  const issue = calculation.issues.find((item) => item.cell === address);
  const commit = () => {
    if (readOnly) return;
    const result = Effect.runSync(Effect.result(commitCell(book, address, draft)));
    if (Result.isFailure(result)) {
      setError(result.failure.message);
      return;
    }
    setBook(result.success);
    setEditing(false);
    setError(undefined);
  };
  const select = (row: number, column: number) => {
    const spill = spillAt(spills, row, column);
    const sourceRow = spill?.row ?? row;
    const sourceColumn = spill?.column ?? column;
    setSelected({ row, column });
    setDraft(readInput(book.toJSON().sheets[0].data[sourceRow]?.[sourceColumn]));
    setEditing(false);
    setError(undefined);
  };
  const edit = (row: number, column: number) => {
    const spill = spillAt(spills, row, column);
    select(spill?.row ?? row, spill?.column ?? column);
    setEditing(true);
  };
  const cancel = () => select(selected.row, selected.column);
  return {
    data: calculation.workbook.sheets[0].data,
    spills,
    readOnly,
    help,
    selected,
    address,
    draft,
    editing,
    error: error ?? issue?.message,
    commit,
    select,
    edit,
    cancel,
    setDraft,
  };
}

export function Spreadsheet() {
  const state = useSpreadsheet();
  return (
    <section
      aria-label="Spreadsheet"
      className="overflow-hidden rounded-lg border bg-card shadow-sm"
    >
      <FormulaBar
        selected={state.address}
        formula={state.draft}
        error={state.error}
        readOnly={state.readOnly}
        onFormulaChange={state.setDraft}
        onRun={state.commit}
      />
      <Grid
        data={state.data}
        spills={state.spills}
        selected={state.selected}
        editing={state.editing}
        draft={state.draft}
        onSelect={state.select}
        onEdit={state.edit}
        onDraftChange={state.setDraft}
        onCommit={state.commit}
        onCancel={state.cancel}
      />
      <div className="flex flex-wrap items-center justify-between gap-2 border-t px-4 py-3 text-xs text-muted-foreground">
        <span className="font-medium text-foreground">Sheet 1</span>
        <p id="formula-help">{state.help}</p>
      </div>
      <p id="formula-error" role="alert" className="px-4 text-sm text-destructive empty:hidden">
        {state.error}
      </p>
    </section>
  );
}
